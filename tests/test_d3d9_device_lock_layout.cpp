TEST(D3D9DeviceLockLayoutTest, GateMustLieBeyondTheCriticalSection) {
    EXPECT_EQ(CriticalSectionSize(CodeArch::X86), 24u);
    EXPECT_EQ(CriticalSectionSize(CodeArch::X64), 40u);
    // lea r8,[rcx+8]; cmp [rcx+disp8],ebx; je +7; call [rip+100h]
    constexpr uintptr_t kAddress = 0x180000000;
    const FakeImports imports({{kAddress + 16 + 0x100, LockCall::Enter}});
    std::vector<uint8_t> code = {0x4C, 0x8D, 0x41, 0x08, 0x39, 0x59, 0x28, 0x74,
                                 0x07, 0x48, 0xFF, 0x15, 0x00, 0x01, 0x00, 0x00};
    EXPECT_TRUE(Decode(code, kAddress, CodeArch::X64, imports).found);
    code[6] = 0x18;  // the x86 gate offset lies inside an x64 CRITICAL_SECTION
    EXPECT_FALSE(Decode(code, kAddress, CodeArch::X64, imports).found);
}

TEST(D3D9DeviceLockLayoutTest, RejectsCallsThatAreNotTheLock) {
    // A hooked or foreign import (here the CFG check slot) is never the lock.
    const FakeImports guardOnly({{kX86GuardCheck, LockCall::Enter}});
    EXPECT_FALSE(Decode(kX86GetDirect3D, 0x100DEDB0, CodeArch::X86, guardOnly).found);
    // Same bytes at another address: the RIP-relative slot no longer resolves.
    EXPECT_FALSE(Decode(kX64GetDirect3D, 0x180092F60, CodeArch::X64, X64Imports()).found);
}

TEST(D3D9DeviceLockLayoutTest, RejectsShapesThatAreNotTheLock) {
    const FakeImports imports({{0x10000000, LockCall::Enter}});
    const std::vector<std::vector<uint8_t>> rejected = {
        // gate inside the CRITICAL_SECTION: cmp [esi+10h],0
        {0x8D, 0x77, 0x04, 0x83, 0x7E, 0x10, 0x00, 0x74, 0x07, 0x56, 0xFF, 0x15, 0x00, 0x00, 0x00, 0x10},
        // the call receives another register than the tested owner (push edi, cmp [esi+..])
        {0x8D, 0x77, 0x04, 0x83, 0x7E, 0x18, 0x00, 0x74, 0x07, 0x57, 0xFF, 0x15, 0x00, 0x00, 0x00, 0x10},
        // compare against a non-zero immediate
        {0x8D, 0x77, 0x04, 0x83, 0x7E, 0x18, 0x01, 0x74, 0x07, 0x56, 0xFF, 0x15, 0x00, 0x00, 0x00, 0x10},
        // jne whose target leaves the scanned code
        {0x8D, 0x77, 0x04, 0x83, 0x7E, 0x18, 0x00, 0x75, 0x40, 0x56, 0xFF, 0x15, 0x00, 0x00, 0x00, 0x10},
        // no lock-owner lea in the function
        {0x8B, 0x77, 0x04, 0x83, 0x7E, 0x18, 0x00, 0x74, 0x07, 0x56, 0xFF, 0x15, 0x00, 0x00, 0x00, 0x10},
        // misaligned owner offset
        {0x8D, 0x77, 0x05, 0x83, 0x7E, 0x18, 0x00, 0x74, 0x07, 0x56, 0xFF, 0x15, 0x00, 0x00, 0x00, 0x10},
        // stack-relative compare: cmp [ebp+18h],0
        {0x8D, 0x77, 0x04, 0x83, 0x7D, 0x18, 0x00, 0x74, 0x07, 0x55, 0xFF, 0x15, 0x00, 0x00, 0x00, 0x10},
        // truncated: the call is cut off
        {0x8D, 0x77, 0x04, 0x83, 0x7E, 0x18, 0x00, 0x74, 0x07, 0x56, 0xFF, 0x15, 0x00, 0x00},
    };
    for (const auto& code : rejected)
        EXPECT_FALSE(Decode(code, 0x20000000, CodeArch::X86, imports).found);
    // The minimal accepted shape, so the rejections above are about their one change.
    const std::vector<uint8_t> accepted = {0x8D, 0x77, 0x04, 0x83, 0x7E, 0x18, 0x00, 0x74,
                                           0x07, 0x56, 0xFF, 0x15, 0x00, 0x00, 0x00, 0x10};
    EXPECT_TRUE(Decode(accepted, 0x20000000, CodeArch::X86, imports).found);
    EXPECT_FALSE(DecodeLockLayout(nullptr, 0, 0, CodeArch::X86, imports).found);
}

TEST(D3D9DeviceLockLayoutTest, X64CompareAndOwnerMoveForms) {
    constexpr uintptr_t kAddress = 0x180000000;
    const FakeImports imports({{kAddress + 0x110, LockCall::Enter}});
    // REX.W cmp qword [rcx+28h],rbx is not the dword gate (slot kept identical).
    const std::vector<uint8_t> qword = {0x4C, 0x8D, 0x41, 0x08, 0x48, 0x39, 0x59, 0x28, 0x74,
                                        0x07, 0x48, 0xFF, 0x15, 0xFF, 0x00, 0x00, 0x00};
    EXPECT_FALSE(Decode(qword, kAddress, CodeArch::X64, imports).found);
    // cmp [rbx+28h],0; je; mov rcx,rbx in its 89 /r encoding; call without REX.W.
    const std::vector<uint8_t> moved = {0x4C, 0x8D, 0x41, 0x08, 0x83, 0x7B, 0x28, 0x00, 0x74,
                                        0x09, 0x48, 0x89, 0xD9, 0xFF, 0x15, 0xFD, 0x00, 0x00, 0x00};
    const LockDecode decode = Decode(moved, kAddress, CodeArch::X64, imports);
    ASSERT_TRUE(decode.found);
    EXPECT_EQ(decode.layout, (LockLayout{8, 0x28}));
    // The owner must reach rcx: a move into rdx is not the lock argument.
    std::vector<uint8_t> wrongArgument = moved;
    wrongArgument[12] = 0xDA;
    EXPECT_FALSE(Decode(wrongArgument, kAddress, CodeArch::X64, imports).found);
}

TEST(D3D9DeviceLockLayoutTest, MultithreadedDeviceNeedsGateAndLiveCriticalSection) {
    const LockLayout layout{8, 0x28};
    const uintptr_t owner = kDevice + 8;
    D3D9FakeMemory memory;
    memory.PutDword(owner + 0x28, 1);
    memory.PutPointer(owner, UINT64_MAX);  // no debug record (the default since Windows 8)
    EXPECT_EQ(CheckDeviceLock(memory, layout, kDevice, true, CodeArch::X64), LockCheck::Match);

    // A debug record must name this section.
    constexpr uintptr_t kDebugInfo = 0x30000000;
    memory.PutPointer(owner, kDebugInfo);
    memory.PutWord(kDebugInfo, 0);
    memory.PutPointer(kDebugInfo + 8, owner);
    EXPECT_EQ(CheckDeviceLock(memory, layout, kDevice, true, CodeArch::X64), LockCheck::Match);
    memory.PutPointer(kDebugInfo + 8, owner + 0x40);
    EXPECT_EQ(CheckDeviceLock(memory, layout, kDevice, true, CodeArch::X64), LockCheck::NotCriticalSection);
    memory.PutPointer(kDebugInfo + 8, owner);
    memory.PutWord(kDebugInfo, 1);  // RTL_RESOURCE_TYPE, not a critical section
    EXPECT_EQ(CheckDeviceLock(memory, layout, kDevice, true, CodeArch::X64), LockCheck::NotCriticalSection);

    // Zeroed memory is never an initialized section.
    memory.PutPointer(owner, 0);
    EXPECT_EQ(CheckDeviceLock(memory, layout, kDevice, true, CodeArch::X64), LockCheck::NotCriticalSection);
    // An unreadable debug record is not a section either.
    memory.PutPointer(owner, 0x40000000);
    EXPECT_EQ(CheckDeviceLock(memory, layout, kDevice, true, CodeArch::X64), LockCheck::NotCriticalSection);
}

TEST(D3D9DeviceLockLayoutTest, RuntimeGateMustMatchCreationFlags) {
    const LockLayout layout{8, 0x28};
    D3D9FakeMemory memory;
    memory.PutDword(kDevice + 8 + 0x28, 0);
    // Single-threaded: the runtime never locks and the section is not read.
    EXPECT_EQ(CheckDeviceLock(memory, layout, kDevice, false, CodeArch::X64), LockCheck::Match);
    EXPECT_EQ(CheckDeviceLock(memory, layout, kDevice, true, CodeArch::X64), LockCheck::GateMismatch);
    memory.PutDword(kDevice + 8 + 0x28, 1);
    EXPECT_EQ(CheckDeviceLock(memory, layout, kDevice, false, CodeArch::X64), LockCheck::GateMismatch);
    // Gate set but the section is unreadable.
    EXPECT_EQ(CheckDeviceLock(memory, layout, kDevice, true, CodeArch::X64), LockCheck::ReadFailed);
    EXPECT_EQ(CheckDeviceLock(memory, layout, 0, false, CodeArch::X64), LockCheck::ReadFailed);
    EXPECT_EQ(CheckDeviceLock(D3D9FakeMemory{}, layout, kDevice, false, CodeArch::X64), LockCheck::ReadFailed);
}

TEST(D3D9DeviceLockLayoutTest, X86SectionUsesThirtyTwoBitPointers) {
    const LockLayout layout{4, 0x18};
    D3D9FakeMemory memory;
    memory.PutDword(kDevice + 4 + 0x18, 1);
    memory.PutPointer(kDevice + 4, UINT32_MAX, 4);
    EXPECT_EQ(CheckDeviceLock(memory, layout, kDevice, true, CodeArch::X86), LockCheck::Match);
    constexpr uintptr_t kDebugInfo = 0x30000000;
    memory.PutPointer(kDevice + 4, kDebugInfo, 4);
    memory.PutWord(kDebugInfo, 0);
    memory.PutPointer(kDebugInfo + 4, kDevice + 4, 4);
    EXPECT_EQ(CheckDeviceLock(memory, layout, kDevice, true, CodeArch::X86), LockCheck::Match);
    EXPECT_STREQ(LockCheckName(LockCheck::NotCriticalSection), "lock-not-critical-section");
}
