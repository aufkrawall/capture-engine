class FakeImports final : public ImportResolver {
public:
    explicit FakeImports(std::map<uintptr_t, LockCall> slots) : slots_(std::move(slots)) {}
    LockCall Resolve(uintptr_t slotAddress) const override {
        const auto it = slots_.find(slotAddress);
        return it == slots_.end() ? LockCall::Other : it->second;
    }

private:
    std::map<uintptr_t, LockCall> slots_;
};

LockDecode Decode(const std::vector<uint8_t>& code, uintptr_t address, CodeArch arch, const ImportResolver& imports) {
    return DecodeLockLayout(code.data(), code.size(), address, arch, imports);
}

